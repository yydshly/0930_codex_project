import {createRequire} from 'node:module';
import {writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
const require=createRequire('C:/Users/yun68/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/package.json');
const {chromium}=require('playwright');
const root=fileURLToPath(new URL('../',import.meta.url));
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1050},reducedMotion:'reduce'});
const checks=[],errors=[];
page.on('pageerror',error=>errors.push(error.message));
const check=(name,passed)=>{assert.ok(passed,name);checks.push({name,passed:true});};
const chosen=()=>page.locator('.case-card[aria-pressed="true"]').getAttribute('data-case-id');
try{
  await page.goto('http://127.0.0.1:8975/#cases',{waitUntil:'networkidle'});
  check('上一例在首个案例禁用',await page.locator('[data-case-step="-1"]').isDisabled());
  await page.locator('[data-detail-tab="thinking"]').click();
  await page.locator('[data-case-step="1"]').click();
  check('连续阅读进入下一例并保留制作思路',await chosen()==='2'&&await page.locator('[data-detail-tab="thinking"]').getAttribute('aria-selected')==='true');
  await page.locator('[data-case-filter="音乐"]').click();
  check('筛选后列表与详情同步第六例',await chosen()==='6'&&(await page.locator('#case-detail h2').innerText()).includes('Python'));
  check('单条筛选两侧切换均禁用',await page.locator('[data-case-step="-1"]').isDisabled()&&await page.locator('[data-case-step="1"]').isDisabled());
  await page.locator('#case-search').fill('not-a-matching-case');
  check('没有匹配时不展示旧详情',await page.locator('#case-detail').isHidden()&&await page.locator('#case-empty').isVisible());
  await page.locator('#reset-case-search').click();
  check('一键恢复全部案例与搜索框',await page.locator('.case-card').count()===10&&await page.locator('#case-search').inputValue()==='');
  await page.locator('#case-search').fill('Meshy');
  check('技术关键词可定位第九例',await page.locator('.case-card').count()===1&&await chosen()==='9');
  await page.locator('#case-search').fill('');
  const pending=[];
  await page.route('https://video.twimg.com/**',route=>pending.push(route));
  await page.locator('#play-original').click();
  check('媒体请求等待时有加载反馈',await page.locator('.media-loading').isVisible()&&await page.locator('#case-media').getAttribute('aria-busy')==='true');
  await page.waitForFunction(()=>document.querySelector('video')?.networkState===2);
  await page.waitForTimeout(100);
  for(const route of pending.splice(0))await route.abort();
  await page.locator('.media-error').waitFor();
  check('模拟网络失败时提供重试与原帖',await page.locator('.media-error #play-original').isVisible()&&await page.locator('.media-error a').getAttribute('href')==='https://x.com/maxt3chno/status/2105216139647127750');
  await page.locator('.media-error #play-original').click();
  check('重试会重新创建播放器',await page.locator('#case-media video').count()===1);
  await page.locator('[data-case-id="1"]').click();
  for(const route of pending.splice(0))await route.abort().catch(()=>{});
  await page.unroute('https://video.twimg.com/**');
  check('切换案例后旧播放器和加载反馈移除',await page.locator('#case-media video').count()===0&&await page.locator('.media-loading').count()===0);
  await page.locator('.start-path [data-product-link="brand-film"]').click();
  check('推荐起点进入正确产品计划',(await page.locator('#product-detail .product-detail-header h3').innerText()).includes('品牌短片'));
  check('默认对比三项优先方向',await page.locator('.decision-card').count()===3&&await page.locator('[data-compare-id][aria-pressed="true"]').count()===3);
  await page.locator('[data-compare-id="training"]').click();
  check('对比项不超过三项且有上限提示',await page.locator('.decision-card').count()===3&&(await page.locator('.decision-status').innerText()).includes('最多'));
  await page.locator('[data-remove-id="showroom"]').click();
  await page.locator('[data-compare-id="training"]').click();
  check('可替换比较方向',await page.locator('.decision-card').count()===3&&await page.locator('[data-compare-id="training"]').getAttribute('aria-pressed')==='true');
  await page.reload({waitUntil:'networkidle'});
  check('刷新后恢复本地选择',await page.locator('[data-compare-id="training"]').getAttribute('aria-pressed')==='true');
  await page.locator('.decision-card [data-product-link="training"]').click();
  check('对比卡能进入对应计划',(await page.locator('#product-detail .product-detail-header h3').innerText()).includes('情境训练'));
  await page.locator('[data-product-filter="优先验证"]').click();
  check('产品筛选会同步匹配的计划',(await page.locator('#product-detail .product-detail-header h3').innerText()).includes('展厅'));
  await page.locator('[data-decision-action="clear"]').click();
  check('清空对比显示可恢复的空状态',await page.locator('.decision-card').count()===0&&await page.locator('.decision-empty').isVisible());
  await page.locator('[data-decision-action="reset"]').click();
  check('恢复三优先方向',await page.locator('.decision-card').count()===3);
  for(const width of [390,768,1440]){
    await page.setViewportSize({width,height:1050});
    for(const view of ['cases','capabilities','products']){
      await page.locator(`[data-view="${view}"]`).click();
      check(`${view}在${width}px无页面横向溢出`,await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
      if(width===390)await page.screenshot({path:root+`assets/qa/${view}-mobile.png`,fullPage:true});
      if(width===1440&&view!=='cases')await page.screenshot({path:root+`assets/qa/${view}-desktop.png`,fullPage:true});
    }
  }
  await page.locator('[data-view="cases"]').click();
  await page.evaluate(()=>scrollTo(0,0));
  await page.screenshot({path:root+'assets/qa/cases-desktop.png'});
  await page.locator('[data-view="products"]').click();
  await page.locator('#product-decision-board').scrollIntoViewIfNeeded();
  await page.screenshot({path:root+'assets/qa/product-decision-desktop.png'});
  check('无JavaScript运行错误',errors.length===0);
  await writeFile(root+'notes/improvements-verification.json',JSON.stringify({checkedAt:'2026-10-02',checks,errors,mediaScope:'Loading, failure and retry UI checked with an intentionally aborted request; source playback evidence remains in media-verification.json.'},null,2)+'\n');
  console.log(JSON.stringify({passed:checks.length,errors}));
}finally{await browser.close();}
